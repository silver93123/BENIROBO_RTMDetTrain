"""오토라벨링 파이프라인 설정.

'내부에 감추고 UI로 노출하지 않는다'는 프로젝트 원칙에 따라
튜닝 상수는 전부 이 파일에 모아둔다. UI 스핀박스로 빼지 말 것.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class AutoLabelConfig:
    # ------------------------------------------------------------------
    # 추론 단계
    # ------------------------------------------------------------------
    # 라벨링용 추론은 학습 평가용보다 낮게 잡는다.
    # 사람이 지우는 비용 << 사람이 새로 그리는 비용 이므로 recall 우선.
    score_thr: float = 0.30
    # 한 장에서 받아들일 최대 인스턴스 수 (폭주 방지)
    max_instances: int = 150
    # 좌우반전 TTA로 불확실도를 측정할지 여부. 추론 비용 2배.
    use_tta_hflip: bool = True
    # TTA 인스턴스 매칭 시 같은 객체로 볼 최소 IoU
    tta_match_iou: float = 0.30

    # ------------------------------------------------------------------
    # 마스크 -> 폴리곤 변환
    # ------------------------------------------------------------------
    # approxPolyDP epsilon = ratio * arcLength.
    # 0.001 -> 정점 100개 이상(편집 지옥), 0.01 -> 모서리 뭉개짐.
    # 0.002~0.004 구간에서 정점 20~50개가 편집하기 좋은 지점.
    approx_eps_ratio: float = 0.0025
    # 이보다 작은 마스크 조각은 노이즈로 보고 버린다 (픽셀 단위)
    min_mask_area: int = 120
    # 관통홀 등 내부 컨투어를 별도 shape(group_id 공유)로 유지할지 여부
    keep_holes: bool = False
    # 정점이 이보다 많으면 epsilon을 키워 재시도
    max_vertices: int = 80

    # ------------------------------------------------------------------
    # 자동 승인 / 우선순위
    # ------------------------------------------------------------------
    # 모든 인스턴스가 이 점수 이상이고 TTA 일치도가 높으면 사람 검수 생략
    auto_accept_score: float = 0.90
    auto_accept_tta_iou: float = 0.85
    # 이 범위를 벗어난 검출 개수는 이상치로 보고 우선 검수
    expected_count_min: int = 1
    expected_count_max: int = 60
    # 검수 대기열 중 상위 몇 %를 'urgent' 큐로 분리할지
    urgent_ratio: float = 0.35

    # ------------------------------------------------------------------
    # 품질 추적
    # ------------------------------------------------------------------
    # 사람이 수정한 폴리곤과 원본 예측의 IoU가 이보다 낮으면
    # '크게 고쳐진 것'으로 집계한다. 라운드별 추이가 모델 개선 지표.
    heavy_edit_iou: float = 0.80


DEFAULT = AutoLabelConfig()